/**
 * Generates includes/Core/launcher-icons.php: the inner SVG markup of the lucide
 * icons that src/app/moduleIcons.tsx maps (so the launcher overlay, which is plain
 * PHP + JS outside the SPA bundle, shows the very same icons as the Modules list),
 * plus the three icons of the launcher chrome. Run after adding an icon there:
 *   node bin/gen-launcher-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const src = readFileSync( join( root, 'src/app/moduleIcons.tsx' ), 'utf8' );
const block = src.slice( src.indexOf( 'const ICONS' ), src.indexOf( '/** Renders a module' ) );
const names = [ ...block.matchAll( /^\t'?([a-z0-9-]+)'?:/gm ) ].map( ( m ) => m[ 1 ] );
const extras = [ 'list', 'chevron-right', 'layout-grid' ];
const all = [ ...new Set( [ ...names, ...extras ] ) ].sort();

const esc = ( s ) => String( s ).replace( /&/g, '&amp;' ).replace( /"/g, '&quot;' );
const out = [];
for ( const name of all ) {
	let file = readFileSync( join( root, 'node_modules/lucide-react/dist/esm/icons', `${ name }.js` ), 'utf8' );
	// Renamed icons are re-exports of the new file.
	const alias = file.match( /from ['"]\.\/([a-z0-9-]+)\.js['"]/ );
	if ( alias ) {
		file = readFileSync( join( root, 'node_modules/lucide-react/dist/esm/icons', `${ alias[ 1 ] }.js` ), 'utf8' );
	}
	const m = file.match( /createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/ );
	if ( ! m ) {
		throw new Error( `No icon node in ${ name }` );
	}
	const nodes = ( 0, eval )( m[ 1 ] );
	const svg = nodes
		.map( ( [ tag, attrs ] ) => `<${ tag } ${ Object.entries( attrs ).filter( ( [ k ] ) => k !== 'key' ).map( ( [ k, v ] ) => `${ k }="${ esc( v ) }"` ).join( ' ' ) }/>` )
		.join( '' );
	out.push( `\t'${ name }' => '${ svg }',` );
}

writeFileSync(
	join( root, 'includes/Core/launcher-icons.php' ),
	`<?php\n/**\n * GENERATED by bin/gen-launcher-icons.mjs from lucide-react (ISC licence). Do not edit by hand.\n *\n * @package UxStudio\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n${ out.join( '\n' ) }\n);\n`
);
console.log( `${ all.length } icons` );
